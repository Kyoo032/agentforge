function labelTexture(text) {
  if (typeof document === "undefined") return null;
  const c = document.createElement("canvas");
  c.width = 256;
  c.height = 128;
  const g = c.getContext("2d");
  g.fillStyle = "#ffd28a";
  g.fillRect(0, 0, 256, 128);
  g.strokeStyle = "#5a3a00";
  g.lineWidth = 6;
  g.strokeRect(3, 3, 250, 122);
  g.fillStyle = "#5a3a00";
  g.font = "bold 44px sans-serif";
  g.textAlign = "center";
  g.textBaseline = "middle";
  g.fillText(text, 128, 64);
  const tex = new THREE.CanvasTexture(c);
  tex.colorSpace = THREE.SRGBColorSpace;
  return tex;
}

function gripEmpty(g, x = 0, y = 0, z = 0, name = "grip") {
  const o = new THREE.Object3D();
  o.name = name;
  o.position.set(x, y, z);
  g.add(o);
}

/** A glossy teardrop, tip up, anchor at its centre. */
function buildTear() {
  const pts = [];
  const N = 16;
  for (let i = 0; i <= N; i++) {
    const t = i / N; // 0 bottom .. 1 tip
    const y = -0.07 + t * 0.19;
    const r = t < 0.55 ? 0.055 * Math.sqrt(1 - ((0.55 - t) / 0.55) ** 2) : 0.055 * (1 - (t - 0.55) / 0.45) ** 1.4;
    pts.push(new THREE.Vector2(Math.max(0.0005, r), y));
  }
  const geo = new THREE.LatheGeometry(pts, 28);
  const mat = new THREE.MeshPhysicalMaterial({ color: 0x8fd8f5, roughness: 0.12, clearcoat: 1, clearcoatRoughness: 0.05 });
  const g = new THREE.Group();
  g.name = "nx-prop-tear";
  g.add(new THREE.Mesh(geo, mat));
  gripEmpty(g, 0, 0, 0, "anchor");
  return g;
}

/** A small glossy pink heart, anchor at its centre. */
function buildHeartMini() {
  const s = new THREE.Shape();
  s.moveTo(0, -0.08);
  s.bezierCurveTo(-0.02, -0.06, -0.09, -0.02, -0.09, 0.03);
  s.bezierCurveTo(-0.09, 0.08, -0.04, 0.1, 0, 0.06);
  s.bezierCurveTo(0.04, 0.1, 0.09, 0.08, 0.09, 0.03);
  s.bezierCurveTo(0.09, -0.02, 0.02, -0.06, 0, -0.08);
  const geo = new THREE.ExtrudeGeometry(s, { depth: 0.04, bevelEnabled: true, bevelThickness: 0.02, bevelSize: 0.015, bevelSegments: 4, curveSegments: 20 });
  geo.translate(0, 0, -0.02);
  const mat = new THREE.MeshPhysicalMaterial({ color: 0xf4a3a3, roughness: 0.3, clearcoat: 0.8, clearcoatRoughness: 0.15 });
  const g = new THREE.Group();
  g.name = "nx-prop-heart-mini";
  g.add(new THREE.Mesh(geo, mat));
  gripEmpty(g, 0, 0, 0, "anchor");
  return g;
}

const BUILTIN = { tear: buildTear, "heart-mini": buildHeartMini };

function unknownPlaceholder(name) {
  const g = new THREE.Group();
  g.name = `nx-prop-${name}`;
  g.userData.placeholder = true;
  const tex = labelTexture(name);
  const box = new THREE.Mesh(new THREE.BoxGeometry(0.2, 0.2, 0.05), new THREE.MeshStandardMaterial({ color: tex ? 0xffffff : 0xffd28a, map: tex }));
  g.add(box);
  gripEmpty(g);
  gripEmpty(g, 0, 0, 0, "anchor");
  return g;
}

function resolveProp(rig, name) {
  if (rig.cache.has(name)) return rig.cache.get(name);
  let obj = null;
  const factory = PROPS[name] ?? BUILTIN[name];
  if (typeof factory === "function") {
    try {
      obj = factory();
    } catch (err) {
      warnOnce(`prop "${name}" threw while building: ${err.message}`);
    }
  } else warnOnce(`no prop named "${name}" (placeholder shown)`);
  if (!obj) obj = unknownPlaceholder(name);
  rig.cache.set(name, obj);
  return obj;
}

const _m = new THREE.Matrix4();
const _q = new THREE.Quaternion();
const _e = new THREE.Euler();
const _s = new THREE.Vector3();
const _p = new THREE.Vector3();

/** Matrix of `node` relative to `obj` (walks up the parents; independent of anything above obj). */
function relativeMatrix(obj, node) {
  const m = new THREE.Matrix4();
  for (let n = node; n && n !== obj; n = n.parent) {
    n.updateMatrix();
    m.premultiply(n.matrix);
  }
  return m;
}

/**
 * The matrix that places `obj` in its parent frame: T(pos) * R(rot XYZ deg) * S(scale) * inverse(marker), where marker is
 * the prop's own `grip` (hand-held, alignGrip) or `anchor` empty (everything else) so that point lands on pos.
 * Exported so poses/build-poses.mjs can compute where a two-handed prop's grips end up.
 */
export function placementMatrix(obj, spec, alignGrip) {
  const pos = spec.pos ?? ZERO3;
  const rot = spec.rot ?? ZERO3;
  const sc = spec.scale ?? 1;
  const sv = Array.isArray(sc) ? sc : [sc, sc, sc];
  _e.set(rot[0] * DEG, rot[1] * DEG, rot[2] * DEG, "XYZ");
  _q.setFromEuler(_e);
  const m = new THREE.Matrix4().compose(new THREE.Vector3(pos[0], pos[1], pos[2]), _q.clone(), new THREE.Vector3(sv[0], sv[1], sv[2]));
  const marker = obj.getObjectByName(alignGrip ? "grip" : "anchor");
  if (marker) m.multiply(relativeMatrix(obj, marker).invert());
  return m;
}

function place(obj, spec, alignGrip) {
  placementMatrix(obj, spec, alignGrip).decompose(obj.position, obj.quaternion, obj.scale);
}

function detachAll(rig) {
  for (const o of rig.attached) o.removeFromParent();
  rig.attached = [];
}

function attach(rig, obj, parent, spec, alignGrip) {
  if (!parent) {
    warnOnce(`no parent for ${obj.name}`);
    return;
  }
  parent.add(obj);
  obj.visible = true;
  place(obj, spec, alignGrip);
  rig.attached.push(obj);
}

/** Shows every companion child of a prop's `body` (the floating tablet, picture, board...) except those named in `hide`. */
function setCompanions(obj, hide) {
  const body = obj.getObjectByName("body");
  if (!body) return;
  for (const c of body.children) c.visible = !(hide ?? []).includes(c.name);
}

/** Clip-time appearance of a prop or fx: hidden before spec.at (frame), popping in with an overshoot when spec.pop. */
function popIn(obj, spec, pose, extraScale) {
  let k = extraScale;
  if (spec.at !== undefined && Number.isFinite(pose.fxFrame)) {
    const local = pose.fxFrame - spec.at;
    if (local < 0) obj.visible = false;
    else if (spec.pop) k *= EASES.back(Math.min(1, local / 4));
  }
  if (k !== 1) obj.scale.multiplyScalar(Math.max(k, 0.001));
}

