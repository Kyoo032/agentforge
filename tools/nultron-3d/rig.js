const DEG = Math.PI / 180;
const AX = { x: new THREE.Vector3(1, 0, 0), y: new THREE.Vector3(0, 1, 0), z: new THREE.Vector3(0, 0, 1) };

export const PIVOT_NAMES = [
  "neck",
  "antenna",
  "shoulder-l",
  "shoulder-r",
  "elbow-l",
  "elbow-r",
  "hand-l",
  "hand-r",
  "hip-l",
  "hip-r",
];
export const STATE_NAMES = Object.keys(POSES.states);
export const EYES = ["open", "blink", "happy", "surprised", "closed"];
// Optional eye variants: used when the model has the node, otherwise the rig shows the fallback instead.
export const OPTIONAL_EYES = { wink: "happy" };
export const MOUTHS = ["idle", "talk", "smile", "sad", "o", "sleep"];
export const HANDS = ["open", "point", "thumb", "hold", "fist"];
export const ATTACH = ["grip-l", "grip-r", "head", "body", "root", "fx"];

