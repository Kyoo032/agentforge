const warned = new Set();
function warnOnce(msg) {
  if (warned.has(msg)) return;
  warned.add(msg);
  // eslint-disable-next-line no-console
  console.warn(`nultron rig: ${msg}`);
}

function bind(root) {
  if (root.userData.nxRig) return root.userData.nxRig;
  const get = (name) => root.getObjectByName(`nx-${name}`) ?? null;
  const pivots = {};
  const missing = [];
  for (const n of PIVOT_NAMES) {
    const o = get(n);
    if (o) pivots[n] = o;
    else missing.push(`nx-${n}`);
  }
  const body = get("body");
  if (!body) missing.push("nx-body");
  const rest = {};
  for (const [n, o] of Object.entries(pivots)) rest[n] = { p: o.position.clone(), q: o.quaternion.clone() };
  if (body) rest.body = { p: body.position.clone(), q: body.quaternion.clone() };
  const variants = {
    eyes: Object.fromEntries([...EYES, ...Object.keys(OPTIONAL_EYES)].map((v) => [v, get(`eyes-${v}`)])),
    mouth: Object.fromEntries(MOUTHS.map((v) => [v, get(`mouth-${v}`)])),
    handL: Object.fromEntries(HANDS.map((v) => [v, get(`hand-l-${v}`)])),
    handR: Object.fromEntries(HANDS.map((v) => [v, get(`hand-r-${v}`)])),
  };
  for (const [group, table] of Object.entries(variants)) {
    for (const [v, o] of Object.entries(table)) if (!o && !(group === "eyes" && v in OPTIONAL_EYES)) missing.push(`variant ${group}:${v}`);
  }
  const rig = {
    pivots,
    body,
    rest,
    variants,
    fxRoot: get("fx"),
    anchors: { "grip-l": get("grip-l"), "grip-r": get("grip-r"), head: get("head"), body, root, fx: get("fx") },
    cache: new Map(),
    attached: [],
    missing,
  };
  if (missing.length) warnOnce(`model lacks ${missing.join(", ")}`);
  root.userData.nxRig = rig;
  return rig;
}

function setVariant(table, group, want) {
  if (want && !(want in table)) warnOnce(`unknown ${group} variant "${want}"`);
  for (const [name, obj] of Object.entries(table)) if (obj) obj.visible = name === want;
}

/** Shows one hand variant and, like character.js setHand(), moves nx-grip-<side> to that variant's grip point. */
function setHandVariant(rig, side, want) {
  setVariant(rig.variants[side === "l" ? "handL" : "handR"], `hand-${side}`, want);
  const hand = rig.pivots[`hand-${side}`];
  const grip = hand?.getObjectByName(`nx-grip-${side}`);
  const g = hand?.userData?.grips?.[want];
  if (grip && g) grip.position.set(g[0], g[1], g[2]);
}

