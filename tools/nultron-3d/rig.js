// Nultron 3D rig: applyPose(root, state, { t, mode, props }).
//
// Owner: poser. Data lives in ./poses.json (the source of truth; this file only interprets it).
//
// WHAT IT DOES
//   Sets the rotation of every pivot in the contract's scene graph, shows exactly one variant of the eyes, mouth and each
//   hand, attaches the state's prop(s) and fx, and evaluates the state's clip or loop when a time is given.
//   Every call rewrites ALL of that from scratch, so applying pose B after pose A gives the same scene as applying B on a
//   fresh model (tests: poses/test/rig.test.mjs).
//
// REST POSE
//   The first call snapshots the model's rest transforms (position + quaternion of every pivot, and of nx-body) into
//   root.userData.nxRig.rest. Pose angles are DELTAS from that snapshot, so the model may bake a rest tilt into a pivot.
//   Nothing else may move the pivots between calls.
//
// ANGLE CONVENTIONS (degrees; every triple is [a, b, c]; left/right are SCREEN-relative, -l is at -X)
//   The same numbers on -l and -r give a mirror-symmetric pose.
//   neck, antenna, body.lean   [nod, turn, tilt]
//                                nod  + = pitch forward (face looks down, antenna tip leans toward +Z)
//                                turn + = face turns toward the viewer's right (+X)
//                                tilt + = top leans clockwise as the viewer sees it (toward +X)
//   shoulder-l/r               [elev, azim, twist]  (the arm hangs along -Y at rest)
//                                elev  = angle between the upper arm and straight down (0 hanging, 90 horizontal, 180 up)
//                                azim  = direction of that swing around the vertical: 0 = straight out sideways,
//                                        90 = straight forward (+Z), -90 = backward
//                                twist = roll about the upper arm; + turns the elbow's bend direction toward the body's
//                                        midline (the bend direction is the arm's local +Z: forward when the arm hangs)
//   elbow-l/r, hand-l/r        [flex, inward, roll]
//                                flex   + = forearm (hand) folds toward the arm's local +Z (forward when hanging)
//                                inward + = swings toward the body's midline
//                                roll   + = roll about the limb axis, toward the midline
//   hip-l/r                    [swing, out, twist]
//                                swing + = leg swings forward (+Z); out + = leg swings away from the midline
//   body.offset                [x, y, z] in units, added to nx-body's rest position
//   Legs stay under the body when it leans: the rig counter-rotates the hips by the lean.
//
// STATE SHAPE (poses.json, "states"): { note, pivots: { neck, antenna, shoulder-l/r, elbow-l/r, hand-l/r, hip-l/r: [a,b,c] },
//   body: { offset, lean }, eyes, mouth, handL, handR, prop: [ {name, attach, pos, rot, scale?, hide?, at?, pop?} ],
//   fx: [ {name, pos, rot?, scale?, at?, pop?} ], clip?, loop? }. poses.json is generated by poses/build-poses.mjs.
//
// CLIPS AND LOOPS (poses.json)
//   state.clip = { fps: 12, frames: [ { f, pivots?, body?, eyes?, mouth?, handL?, handR?, ease? }, ... ] }
//     frames are sparse keyframes at frame numbers f (12 fps; also pscale = prop scale multiplier). A channel a keyframe does not list holds the state's
//     still value. After the last keyframe the pose is the still pose exactly, so a one-shot ends on the still frame.
//     ease (on the keyframe a segment ARRIVES at): linear | in | out | inout | back. Variants (eyes, mouth, hands) step.
//   state.loop = { fps, frames: [...] }  same keyframe shape, cyclic: period = frames.length / fps, interpolation wraps.
//   applyPose(root, state, { t }) with t in seconds evaluates the clip (default) or the loop (mode: "loop", or when the
//   state has no clip). Without t the pose is the still one.
//
// PROPS
//   state.prop = { name, attach, pos?, rot?, scale? } or an array of them. attach is
//     "grip-l" | "grip-r"   child of nx-grip-l/r; the prop's own child object named "grip" is put on the grip point
//     "head"                child of nx-head
//     "body"                child of nx-body (follows bob and lean)
//     "root" | "fx"         child of nx-root / nx-fx
//   pos [x,y,z] is in the parent's frame (units), rot [x,y,z] degrees Euler XYZ (about the grip for hand-held props),
//   hide [names] hides those companion children of the prop ("tablet", "picture", "board", ...) so the same piece can
//   be placed on its own; scale a number or [sx,sy,sz] (a negative component mirrors the prop). Hand-held props are placed by their `grip` empty,
//   everything else by its `anchor` empty. at / pop: hidden before clip frame `at`, popping in with an overshoot.
//   Props come from props.js PROPS[name]() (fx too: thinking, surprised, sparks, celebrating, lets-go, wave, sleep); the rig
//   itself builds "tear" and "heart-mini"; an unknown name shows a labelled box.
//   state.fx = [ { name, pos, rot?, scale?, at?, pop? } ]  child of nx-fx, positions in nx-root's frame.

