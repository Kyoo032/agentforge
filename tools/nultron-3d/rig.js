const isPropTable = (o) => {
  const vals = Object.values(o);
  return vals.length > 0 && vals.every((v) => typeof v === "function");
};

/** What a state offers beyond its still pose. */
export function poseInfo(state) {
  const def = POSES.states[state];
  if (!def) throw new Error(`nultron rig: unknown state "${state}"`);
  return {
    note: def.note ?? "",
    hasClip: Boolean(def.clip),
    clipSeconds: poseDuration(state, "clip"),
    hasLoop: Boolean(def.loop),
    loopFps: def.loop?.fps ?? 0,
    loopSeconds: poseDuration(state, "loop"),
    props: [].concat(def.prop ?? []).map((p) => p.name),
    fx: (def.fx ?? []).map((f) => f.name),
  };
}

/**
 * Puts `root` (the nx-root group from buildNultron) into `state`.
 * @param {THREE.Object3D} root
 * @param {string} state one of STATE_NAMES
 * @param {{ t?: number, mode?: "clip" | "loop" | "still", props?: Record<string, () => THREE.Object3D> } | Record<string, () => THREE.Object3D>} [options]
 *   an options object, or (as scene-main.js does) the PROPS table itself
 * @returns {{ state: string, t: number | undefined }}
 */
export function applyPose(root, state, options) {
  let opts = options ?? {};
  // scene-main.js passes the PROPS table itself as the third argument: accept that as well as an options object.
  if (isPropTable(opts)) {
    setProps(opts);
    opts = {};
  }
  if (opts.props) setProps(opts.props);
  const def = POSES.states[state];
  if (!def) throw new Error(`nultron rig: unknown state "${state}"`);
  const rig = bind(root);
  const pose = evaluatePose(state, opts);

  // Body: rest position + offset, rest rotation * lean; hips undo the lean so the legs stay plumb.
  const leanQ = headQuat(pose.lean);
  if (rig.body) {
    rig.body.position.copy(rig.rest.body.p).add(_p.set(pose.offset[0], pose.offset[1], pose.offset[2]));
    rig.body.quaternion.copy(rig.rest.body.q).multiply(leanQ);
  }
  const leanInv = leanQ.clone().invert();

  for (const n of PIVOT_NAMES) {
    const o = rig.pivots[n];
    if (!o) continue;
    o.position.copy(rig.rest[n].p);
    const delta = pivotQuat(n, pose.pivots[n]);
    if (n.startsWith("hip")) delta.premultiply(leanInv);
    o.quaternion.copy(rig.rest[n].q).multiply(delta);
  }

  const eyes = rig.variants.eyes[pose.eyes] || !(pose.eyes in OPTIONAL_EYES) ? pose.eyes : OPTIONAL_EYES[pose.eyes];
  setVariant(rig.variants.eyes, "eyes", eyes);
  setVariant(rig.variants.mouth, "mouth", pose.mouth);
  setHandVariant(rig, "l", pose.handL);
  setHandVariant(rig, "r", pose.handR);

  // Props and fx: detach everything the previous call attached, then attach this state's.
  detachAll(rig);
  const props = def.prop ? (Array.isArray(def.prop) ? def.prop : [def.prop]) : [];
  for (const spec of props) {
    if (!ATTACH.includes(spec.attach)) {
      warnOnce(`state "${state}": bad attach "${spec.attach}"`);
      continue;
    }
    const obj = resolveProp(rig, spec.name);
    attach(rig, obj, rig.anchors[spec.attach], spec, spec.attach.startsWith("grip"));
    setCompanions(obj, spec.hide);
    popIn(obj, spec, pose, pose.pscale);
  }
  const fxList = def.fx ?? [];
  for (const spec of fxList) {
    const obj = resolveProp(rig, spec.name);
    // Two entries with the same fx name need their own instance.
    const inst = rig.attached.includes(obj) ? obj.clone(true) : obj;
    attach(rig, inst, rig.fxRoot ?? root, spec, false);
    popIn(inst, spec, pose, 1);
  }

  root.updateMatrixWorld(true);
  return { state, t: opts.t };
}

